from datetime import date
import logging
from typing import Any, Dict, List, Optional, Union
from pydantic import BaseModel, Field

from config import settings
from nlp.classification import IncidentCategory, classify_incident_categories
from nlp.entities import ExtractedFact, extract_all_facts
from nlp.legal_matching import (
    ElementMatchResult,
    ElementStatus,
    FollowUpQuestion,
    evaluate_element_against_facts,
    generate_follow_up_questions,
)
from nlp.preprocessing import preprocess_text
from nlp.retrieval import (
    CandidateProvision,
    LegalCorpusIndex,
    get_corpus_index,
    is_out_of_scope_civil_incident,
)

logger = logging.getLogger("lexilaw.offense_decoder")

LEGAL_DISCLAIMER = (
    "This analysis is generated by LexiLaw for educational, informational, and preliminary research "
    "purposes only. It does not constitute formal legal advice, representation, or an authoritative "
    "determination of guilt, criminal liability, or statutory violation. Legal outcomes depend on "
    "admissible evidence, judicial discretion, and formal procedure. Consult a licensed legal advocate "
    "for actionable legal counsel."
)


class ContextualAnswer(BaseModel):
    """Answer provided by user to a previous follow-up question."""

    question_id: str = Field(..., description="ID of the follow-up question, e.g. Q_IPC_S419_ELEM_1")
    answer: str = Field(..., description="User's clarifying response text")


class OffenseAnalysisRequest(BaseModel):
    """Input request payload for incident analysis."""

    incident_text: str = Field(..., description="Ordinary-language description of the incident")
    contextual_answers: Optional[List[ContextualAnswer]] = Field(
        default=None, description="Optional list of answers to clarifying follow-up questions"
    )
    top_k: Optional[int] = Field(
        default=5, ge=1, le=20, description="Maximum number of candidate provisions to return (1-20)"
    )
    incident_date: Optional[Union[date, str]] = Field(
        default=None, description="Optional date or year of the incident for temporal law selection"
    )


class EvaluatedCandidateProvision(BaseModel):
    """Evaluated statutory candidate with element comparisons and provenance."""

    provision_id: str
    act_name: str
    section_id: str
    title: str
    jurisdiction: str
    official_source_url: str
    source_authority: str
    source_verified: bool
    effective_from: Optional[str] = None
    effective_to: Optional[str] = None
    version_label: str
    penalty_displayed: Optional[str] = None
    plain_language_summary: str
    explanation: str
    lexical_score: float
    semantic_score: Optional[float] = None
    relevance_score: float
    element_matches: List[ElementMatchResult]
    supported_elements_count: int
    missing_elements_count: int
    contradicted_elements_count: int


class OffenseAnalysisResponse(BaseModel):
    """Structured evidence-grounded response for incident analysis."""

    request_id: str
    extracted_facts: List[ExtractedFact]
    incident_categories: List[IncidentCategory]
    candidate_provisions: List[EvaluatedCandidateProvision]
    follow_up_questions: List[FollowUpQuestion]
    uncertainty_notes: List[str]
    disclaimer: str
    no_reliable_match: bool
    no_reliable_match_explanation: Optional[str] = None


def analyze_incident(
    request: OffenseAnalysisRequest,
    request_id: str,
    custom_index: Optional[LegalCorpusIndex] = None,
) -> OffenseAnalysisResponse:
    """Orchestrate the 9-step Legal Offense Decoder workflow.

    Never claims an offense occurred or that anyone is guilty.
    """
    text = request.incident_text.strip()
    if not text:
        raise ValueError("Incident text must not be empty.")

    if len(text) > settings.max_text_length:
        raise ValueError(
            f"Input text exceeds maximum allowed length of {settings.max_text_length} characters."
        )

    # 1. Preprocess text
    doc = preprocess_text(text)

    # 2. Extract structured facts
    extraction = extract_all_facts(doc.normalized_text)
    all_facts = extraction.facts

    # 3. Classify into provisional categories
    categories = classify_incident_categories(doc.normalized_text)

    # 4. Map contextual answers for quick lookup
    answers_map: Dict[str, str] = {}
    if request.contextual_answers:
        for ca in request.contextual_answers:
            answers_map[ca.question_id] = ca.answer

    # 5. Retrieve candidate provisions from corpus index
    index = custom_index or get_corpus_index()
    top_k = request.top_k or settings.default_top_k
    candidates = index.retrieve(
        doc.normalized_text,
        top_k=top_k,
        incident_date=request.incident_date,
    )

    evaluated_candidates: List[EvaluatedCandidateProvision] = []
    follow_up_questions: List[FollowUpQuestion] = []

    # 6. Evaluate elements for retrieved candidates
    is_civil = is_out_of_scope_civil_incident(doc.normalized_text)
    if not candidates:
        no_reliable_match = True
        if is_civil:
            no_match_expl = (
                "The incident describes a civil, regulatory, or administrative matter "
                "(such as tenancy dispute, traffic fine, municipal taxation, or consumer service grievance) "
                "that falls outside the indexed criminal and penal provisions of LexiLaw."
            )
        else:
            no_match_expl = (
                "No candidate provisions met the minimum relevance threshold in the local verified corpus. "
                "The incident may fall outside the current indexed statutes or require professional legal review."
            )
    else:
        no_reliable_match = False
        no_match_expl = None

        for cand in candidates:
            prov = cand.provision
            element_evaluations: List[ElementMatchResult] = []

            for elem in prov.legal_elements:
                eval_res = evaluate_element_against_facts(
                    element=elem,
                    facts=all_facts,
                    doc=doc,
                    contextual_answers=answers_map,
                    provision_id=prov.id,
                )
                element_evaluations.append(eval_res)

            supp_count = sum(1 for e in element_evaluations if e.status == ElementStatus.SUPPORTED)
            miss_count = sum(1 for e in element_evaluations if e.status == ElementStatus.NOT_ESTABLISHED)
            contra_count = sum(1 for e in element_evaluations if e.status == ElementStatus.CONTRADICTED)

            # Generate grounded explanation
            explanation_parts = [
                f"{prov.act_name} {prov.section_id} ({prov.title}) was identified with relevance score {cand.relevance_score:.2f}."
            ]
            if supp_count > 0:
                explanation_parts.append(f"{supp_count} element(s) appear supported by stated facts.")
            if miss_count > 0:
                explanation_parts.append(
                    f"{miss_count} essential legal element(s) are not established from the provided description."
                )
            if contra_count > 0:
                explanation_parts.append(
                    f"{contra_count} element(s) appear contradicted by the facts or contextual clarifications."
                )

            explanation = " ".join(explanation_parts)

            evaluated_candidates.append(
                EvaluatedCandidateProvision(
                    provision_id=prov.id,
                    act_name=prov.act_name,
                    section_id=prov.section_id,
                    title=prov.title,
                    jurisdiction=prov.jurisdiction,
                    official_source_url=prov.official_source_url,
                    source_authority=prov.source_authority,
                    source_verified=prov.source_verified,
                    effective_from=prov.effective_from,
                    effective_to=prov.effective_to,
                    version_label=prov.version_label,
                    penalty_displayed=cand.penalty_displayed,
                    plain_language_summary=prov.plain_language_summary,
                    explanation=explanation,
                    lexical_score=cand.lexical_score,
                    semantic_score=cand.semantic_score,
                    relevance_score=cand.relevance_score,
                    element_matches=element_evaluations,
                    supported_elements_count=supp_count,
                    missing_elements_count=miss_count,
                    contradicted_elements_count=contra_count,
                )
            )

            # Collect follow-up questions for unestablished elements
            unestablished = [e for e in element_evaluations if e.status == ElementStatus.NOT_ESTABLISHED]
            if unestablished:
                questions = generate_follow_up_questions(prov, unestablished)
                # Keep up to 3 questions per candidate to avoid overwhelming the user
                follow_up_questions.extend(questions[:3])

    uncertainty_notes = [
        "Identified provisions are preliminary hypotheses based solely on user-provided descriptions.",
        "Unestablished elements indicate missing factual details, not formal legal negation.",
        "LexiLaw does not assert guilt, criminal culpability, or definitive statutory applicability.",
    ]

    has_ipc = any(c.act_name == "Indian Penal Code, 1860" for c in evaluated_candidates)
    has_bns = any(c.act_name == "Bharatiya Nyaya Sanhita, 2023" for c in evaluated_candidates)
    has_uncommenced = any(c.provision_id == "BNS_2023_S106_SUB2_UNCOMMENCED" for c in evaluated_candidates)

    if has_ipc and has_bns:
        uncertainty_notes.append(
            "Both Bharatiya Nyaya Sanhita (BNS 2023) and legacy Indian Penal Code (IPC 1860) provisions were identified. BNS governs offenses committed on or after 1 July 2024; IPC governs offenses committed on or before 30 June 2024 under Section 358 BNS transitional savings and Article 20(1) of the Constitution of India."
        )
    elif has_ipc:
        uncertainty_notes.append(
            "Legacy IPC (1860) provisions apply historically to conduct committed on or before 30 June 2024 under Section 358 BNS transitional savings."
        )
    elif has_bns:
        uncertainty_notes.append(
            "Bharatiya Nyaya Sanhita (BNS 2023) provisions apply to conduct committed on or after 1 July 2024."
        )

    if has_uncommenced:
        uncertainty_notes.append(
            "Notice: Section 106(2) of the BNS was excluded from commencement under Ministry of Home Affairs Notification S.O. 850(E) and is not currently in force."
        )

    return OffenseAnalysisResponse(
        request_id=request_id,
        extracted_facts=all_facts,
        incident_categories=categories,
        candidate_provisions=evaluated_candidates,
        follow_up_questions=follow_up_questions[:6],  # Global cap of 6 top questions
        uncertainty_notes=uncertainty_notes,
        disclaimer=LEGAL_DISCLAIMER,
        no_reliable_match=no_reliable_match,
        no_reliable_match_explanation=no_match_expl,
    )
